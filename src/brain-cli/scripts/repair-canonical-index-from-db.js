"use strict";

const fs = require("fs");
const path = require("path");
const Database = require("better-sqlite3");
const { acquireLock } = require("../src/lock");
const { validate } = require("../src/validate");
const {
  calculateHash,
  generateDigestLine,
  readJsonl,
  safeReadJson,
  writeJsonl,
} = require("../src/utils");

const INDEX_FILES = ["records.jsonl", "records_digest.txt", "manifest.json"];

function normalizeRef(value) {
  return String(value || "").replace(/\\/g, "/").replace(/^\.\//, "").normalize("NFC");
}

function parseTags(value) {
  if (Array.isArray(value)) return value;
  if (!value) return [];
  try {
    const parsed = JSON.parse(value);
    if (Array.isArray(parsed)) return parsed;
  } catch { /* comma-delimited legacy value */ }
  return String(value).split(",").map(tag => tag.trim()).filter(Boolean);
}

function resolveSourcePath(brainRoot, sourceRef) {
  const root = path.resolve(brainRoot);
  const resolved = path.resolve(root, normalizeRef(sourceRef));
  if (resolved !== root && !resolved.startsWith(root + path.sep)) return null;
  return resolved;
}

function rowToRecord(brainRoot, row) {
  const sourceRef = normalizeRef(row.source_ref);
  const sourcePath = resolveSourcePath(brainRoot, sourceRef);
  if (!sourcePath || !fs.existsSync(sourcePath) || !fs.statSync(sourcePath).isFile()) return null;
  return {
    recordId: row.record_id,
    scopeType: row.scope_type,
    scopeId: row.scope_id,
    type: row.type,
    title: row.title,
    summary: row.summary,
    tags: parseTags(row.tags),
    sourceType: row.source_type,
    sourceRef,
    status: row.status,
    replacedBy: row.replaced_by || null,
    deprecationReason: row.deprecation_reason || null,
    updatedAt: row.updated_at,
    contentHash: row.content_hash || calculateHash(sourcePath),
  };
}

function loadState(brainRoot, options = {}) {
  const recordsPath = path.join(brainRoot, "90_index", "records.jsonl");
  const dbPath = path.join(brainRoot, "90_index", "records.db");
  if (!fs.existsSync(recordsPath)) throw new Error(`records.jsonl 없음: ${recordsPath}`);
  if (!fs.existsSync(dbPath)) throw new Error(`records.db 없음: ${dbPath}`);

  const records = readJsonl(recordsPath);
  const jsonIds = new Set(records.map(record => record.recordId));
  const db = new Database(dbPath, { readonly: true, fileMustExist: true });
  let rows;
  try {
    rows = db.prepare(`
      SELECT record_id, scope_type, scope_id, type, title, summary, tags,
             source_ref, source_type, status, replaced_by, deprecation_reason,
             updated_at, content_hash
      FROM records
      ORDER BY updated_at, record_id
    `).all();
  } finally {
    db.close();
  }

  const requestedRecordIds = new Set(options.recordIds || []);
  const candidates = [];
  let dbOnlyMissingSource = 0;
  for (const row of rows) {
    if (requestedRecordIds.size > 0 && !requestedRecordIds.has(row.record_id)) continue;
    if (jsonIds.has(row.record_id)) continue;
    const record = rowToRecord(brainRoot, row);
    if (record) candidates.push(record);
    else dbOnlyMissingSource++;
  }
  return { records, candidates, dbRows: rows.length, dbOnlyMissingSource };
}

function planRepair(brainRoot, options = {}) {
  const state = loadState(brainRoot, options);
  return {
    brainRoot: path.resolve(brainRoot),
    requestedRecordIds: options.recordIds || [],
    jsonRecords: state.records.length,
    dbRecords: state.dbRows,
    recoverable: state.candidates.length,
    dbOnlyMissingSource: state.dbOnlyMissingSource,
    sampleRecordIds: state.candidates.slice(0, 10).map(record => record.recordId),
  };
}

function categoryFor(sourceRef) {
  if (sourceRef.startsWith("00_user/")) return "user";
  if (sourceRef.startsWith("10_projects/")) return "project";
  if (sourceRef.startsWith("30_topics/")) return "topic";
  if (sourceRef.startsWith("40_wiki/")) return "wiki";
  return "index";
}

function updateManifest(brainRoot, manifest, candidates) {
  if (!Array.isArray(manifest.files)) manifest.files = [];
  const knownPaths = new Set(manifest.files.map(entry => normalizeRef(entry.path).toLowerCase()));
  for (const record of candidates) {
    const key = record.sourceRef.toLowerCase();
    if (knownPaths.has(key)) continue;
    const sourcePath = resolveSourcePath(brainRoot, record.sourceRef);
    const stat = fs.statSync(sourcePath);
    manifest.files.push({
      path: record.sourceRef,
      hash: calculateHash(sourcePath),
      size: stat.size,
      updatedAt: stat.mtime.toISOString(),
      category: categoryFor(record.sourceRef),
    });
    knownPaths.add(key);
  }
  manifest.updatedAt = new Date().toISOString();
  return manifest;
}

function writeDigest(filePath, records) {
  const header = "# Brain records_digest.txt\n# Format: recordId | title | summary | tags | status | type | sourceType | updatedAt\n# Auto-generated by brain-cli repair-canonical-index-from-db. Do not edit manually.\n";
  fs.writeFileSync(filePath, header + records.map(generateDigestLine).join("\n") + "\n", "utf-8");
}

function copyBackups(indexDir, backupDir) {
  fs.mkdirSync(backupDir, { recursive: false });
  for (const name of INDEX_FILES) {
    const source = path.join(indexDir, name);
    if (!fs.existsSync(source)) throw new Error(`백업 대상 없음: ${source}`);
    fs.copyFileSync(source, path.join(backupDir, name));
  }
}

function restoreBackups(indexDir, backupDir) {
  for (const name of INDEX_FILES) {
    const backup = path.join(backupDir, name);
    if (fs.existsSync(backup)) fs.copyFileSync(backup, path.join(indexDir, name));
  }
}

function applyRepair(brainRoot, options = {}) {
  if (!Array.isArray(options.recordIds) || options.recordIds.length === 0) {
    throw new Error("운영 적용은 --record-id=<id[,id]>를 명시해야 합니다.");
  }
  const indexDir = path.join(brainRoot, "90_index");
  const lock = acquireLock(brainRoot, { staleMs: 30000, timeoutMs: 30000 });
  let backupDir = null;
  const tmpPaths = INDEX_FILES.map(name => path.join(indexDir, `${name}.tmp`));
  try {
    const state = loadState(brainRoot, options);
    if (state.candidates.length === 0) {
      return { ...planRepair(brainRoot, options), applied: false, recovered: 0, backupDir: null };
    }
    const merged = state.records.concat(state.candidates);
    const ids = new Set();
    for (const record of merged) {
      if (ids.has(record.recordId)) throw new Error(`recordId 중복: ${record.recordId}`);
      ids.add(record.recordId);
    }

    const stamp = new Date().toISOString().replace(/[:.]/g, "-");
    backupDir = path.join(indexDir, `_backup-memory-integrity-${stamp}`);
    copyBackups(indexDir, backupDir);

    writeJsonl(path.join(indexDir, "records.jsonl.tmp"), merged);
    writeDigest(path.join(indexDir, "records_digest.txt.tmp"), merged);
    const manifestResult = safeReadJson(path.join(indexDir, "manifest.json"));
    if (!manifestResult.ok) throw new Error(`manifest 읽기 실패: ${manifestResult.error}`);
    const manifest = updateManifest(brainRoot, manifestResult.data, state.candidates);
    fs.writeFileSync(path.join(indexDir, "manifest.json.tmp"), JSON.stringify(manifest, null, 2) + "\n", "utf-8");

    const validation = validate(brainRoot, { tmpMode: true });
    if (!validation.passed) throw new Error(`복구 tmp 검증 실패: ${validation.errors.join("; ")}`);

    for (const name of INDEX_FILES) {
      fs.renameSync(path.join(indexDir, `${name}.tmp`), path.join(indexDir, name));
    }
    return {
      brainRoot: path.resolve(brainRoot),
      applied: true,
      before: state.records.length,
      recovered: state.candidates.length,
      after: merged.length,
      dbOnlyMissingSource: state.dbOnlyMissingSource,
      backupDir,
    };
  } catch (error) {
    if (backupDir) restoreBackups(indexDir, backupDir);
    throw error;
  } finally {
    for (const tmpPath of tmpPaths) {
      try { if (fs.existsSync(tmpPath)) fs.unlinkSync(tmpPath); } catch { /* best effort */ }
    }
    lock.release();
  }
}

function main() {
  const args = { root: null, apply: false, recordIds: [] };
  for (const arg of process.argv.slice(2)) {
    if (arg === "--apply") args.apply = true;
    else if (arg.startsWith("--record-id=")) args.recordIds.push(...arg.slice(12).split(",").filter(Boolean));
    else if (!arg.startsWith("--") && !args.root) args.root = arg;
  }
  if (!args.root) throw new Error("사용법: node repair-canonical-index-from-db.js <brainRoot> [--record-id=<id[,id]>] [--apply]");
  const brainRoot = path.resolve(args.root);
  const result = args.apply ? applyRepair(brainRoot, args) : planRepair(brainRoot, args);
  process.stdout.write(JSON.stringify(result, null, 2) + "\n");
}

if (require.main === module) main();

module.exports = { applyRepair, planRepair };
